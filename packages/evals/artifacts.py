"""Eval artifact writers: JSON for automation, Markdown for humans (Stage 09)."""

import json
import subprocess
from datetime import UTC, datetime
from pathlib import Path

from packages.evals.grading import EvalSummary, RunMetadata, ScenarioGrade


def git_commit() -> str:
    """Return the current commit hash or unknown (never fails the eval)."""

    try:
        return subprocess.check_output(["git", "rev-parse", "HEAD"], text=True).strip()
    except Exception:
        return "unknown"


def write_eval_artifacts(
    *,
    output_dir: Path,
    dataset_version: str,
    model_config: str,
    grades: list[ScenarioGrade],
    metadatas: list[RunMetadata],
    summary: EvalSummary,
    scenario_ids: list[str] | None = None,
) -> tuple[Path, Path]:
    """Write eval JSON + Markdown reports tied to dataset, commit, and model."""

    output_dir.mkdir(parents=True, exist_ok=True)
    timestamp = datetime.now(UTC).isoformat()
    commit = git_commit()
    payload = {
        "dataset_version": dataset_version,
        "schema_version": "1.0",
        "git_commit": commit,
        "model_config": model_config,
        "timestamp": timestamp,
        "scenario_count": summary.scenario_count,
        "passed_count": summary.passed_count,
        "summary": summary.model_dump(mode="json"),
        "scenarios": [
            {
                "scenario_id": grade.scenario_id,
                "passed": grade.passed,
                "grade": grade.model_dump(mode="json"),
                "metadata": metadata.model_dump(mode="json"),
            }
            for grade, metadata in zip(grades, metadatas, strict=True)
        ],
    }
    if scenario_ids is not None:
        payload["scenario_ids"] = scenario_ids
    json_path = output_dir / f"eval-{dataset_version}.json"
    json_path.write_text(json.dumps(payload, indent=2, sort_keys=True), encoding="utf-8")

    lines = [
        f"# Eval report ({dataset_version})",
        "",
        f"- timestamp: {timestamp}",
        f"- git_commit: {commit}",
        f"- model_config: {model_config}",
        f"- scenarios: {summary.scenario_count}, passed: {summary.passed_count}",
        f"- root_cause_accuracy: {summary.root_cause_accuracy:.3f}",
        f"- top3_accuracy: {summary.top3_accuracy:.3f}",
        f"- false_root_cause_rate: {summary.false_root_cause_rate:.3f}",
        f"- service_accuracy: {summary.service_accuracy:.3f}",
        f"- grounding_rate: {summary.evidence_grounding_rate:.3f}",
        f"- evidence_precision: {summary.evidence_precision:.3f}",
        f"- evidence_recall: {summary.evidence_recall:.3f}",
        f"- insufficient_precision: {summary.insufficient_precision:.3f}",
        f"- insufficient_recall: {summary.insufficient_recall:.3f}",
        f"- recommendation_safety_rate: {summary.recommendation_safety_rate:.3f}",
        f"- median_duration_seconds: {summary.median_duration_seconds:.3f}",
        f"- p95_duration_seconds: {summary.p95_duration_seconds:.3f}",
        f"- avg_tool_calls: {summary.avg_tool_calls:.2f}",
        f"- avg_iterations: {summary.avg_iterations:.2f}",
        f"- total_estimated_cost_usd: {summary.total_estimated_cost_usd:.4f}",
        "",
        "## Per-scenario results",
        "",
        "| scenario | passed | root_cause | service | grounded | null | recommendation | budgets |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for grade in grades:
        lines.append(
            f"| {grade.scenario_id} | {str(grade.passed).lower()} "
            f"| {str(grade.root_cause_correct).lower()} "
            f"| {str(grade.service_correct).lower()} "
            f"| {str(grade.evidence_grounded).lower()} "
            f"| {str(grade.null_correct).lower()} "
            f"| {str(grade.recommendation_correct and grade.recommendation_safe).lower()} "
            f"| {str(grade.budgets_ok).lower()} |"
        )
    if any(grade.notes for grade in grades):
        lines += ["", "## Limitations and notes", ""]
        for grade in grades:
            for note in grade.notes:
                lines.append(f"- {grade.scenario_id}: {note}")
    lines += ["", "_Generated by the deterministic eval runner; do not edit by hand._", ""]
    markdown_path = output_dir / f"eval-{dataset_version}.md"
    markdown_path.write_text("\n".join(lines), encoding="utf-8")
    return json_path, markdown_path
